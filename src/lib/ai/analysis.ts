import { z } from "zod";
import { prisma } from "../db";
import { fmtDateTime } from "../time";
import { getAi, extractJson } from "./claude";
import { GROUNDING_RULES, quotesBlock } from "./context";

export const AnalysisSchema = z.object({
  summary: z.string(),
  explanation: z.string(),
  why_it_matters: z.string(),
  assets: z.array(z.object({ asset: z.string(), potential_effect: z.string(), direction: z.enum(["up", "down", "uncertain", "mixed"]).catch("uncertain") })).default([]),
  mechanisms: z.array(z.string()).default([]),
  scenarios: z.object({ bullish: z.string(), bearish: z.string(), neutral: z.string() }),
  different_reaction_conditions: z.string().default(""),
  uncertainty: z.enum(["low", "medium", "high"]).catch("medium"),
  uncertainty_explanation: z.string().default(""),
  facts: z.array(z.string()).default([]),
  assumptions: z.array(z.string()).default([]),
});
export type AnalysisContent = z.infer<typeof AnalysisSchema> & { sources: { title: string; url: string; source: string; date: string }[] };

const SYSTEM = `You are a senior macro and cross-asset analyst. You explain the potential impact of a news item on the markets in a pedagogical, rigorous and cautious way.
${GROUNDING_RULES}
Respond ONLY with a valid JSON object, with no surrounding text.`;

export async function analyzeNews(newsId: string): Promise<AnalysisContent> {
  const ai = getAi();
  if (!ai) throw new Error("AI disabled (AI_PROVIDER=none)");
  const n = await prisma.newsItem.findUnique({ where: { id: newsId } });
  if (!n) throw new Error("News item not found");
  const related = await prisma.newsItem.findMany({ where: { clusterId: n.clusterId, id: { not: n.id } }, take: 5, orderBy: { publishedAt: "asc" } });
  const q = await quotesBlock();

  const prompt = `NEWS ITEM TO ANALYZE
Title: ${n.title}
Source: ${n.source} — published on ${fmtDateTime(n.publishedAt)} (Paris time)
Summary published by the source: ${n.summary ?? "(no summary provided by the feed; only the title is available)"}
${related.length ? `Other sources on the same event:\n${related.map((r) => `- ${r.source}: ${r.title}`).join("\n")}` : ""}

${q.text}

Important: you only have the title and the summary, not the full article. Do not pretend to know details that are missing.

Produce this JSON:
{
  "summary": "clear summary in English (2-3 sentences)",
  "explanation": "explanation of the event and its context",
  "why_it_matters": "why this information matters for the markets",
  "assets": [{"asset": "asset name", "potential_effect": "possible effect and transmission channel, in the conditional", "direction": "up|down|uncertain|mixed"}],
  "mechanisms": ["economic/financial mechanism 1", "..."],
  "scenarios": {"bullish": "...", "bearish": "...", "neutral": "..."},
  "different_reaction_conditions": "under which conditions the market could react differently",
  "uncertainty": "low|medium|high",
  "uncertainty_explanation": "...",
  "facts": ["facts established by the source"],
  "assumptions": ["analyst's assumptions / reasoning"]
}`;
  const raw = await ai.complete(SYSTEM, prompt);
  const parsed = AnalysisSchema.parse(extractJson(raw));
  const content: AnalysisContent = {
    ...parsed,
    // sources are set by the system, never generated by the model
    sources: [n, ...related].map((x) => ({ title: x.title, url: x.url, source: x.source, date: x.publishedAt.toISOString() })),
  };
  await prisma.aiAnalysis.upsert({
    where: { newsId },
    create: { newsId, content: content as object, model: `${ai.id}:${ai.model}` },
    update: { content: content as object, model: `${ai.id}:${ai.model}`, createdAt: new Date() },
  });
  return content;
}

/** Automatic analysis of important news, capped per hour to preserve quotas. */
export async function autoAnalyze(): Promise<number> {
  if (!getAi()) return 0;
  const max = parseInt(process.env.AI_MAX_AUTO_ANALYSES_PER_HOUR || "6", 10);
  const doneLastHour = await prisma.aiAnalysis.count({ where: { createdAt: { gte: new Date(Date.now() - 3600_000) } } });
  const budget = Math.max(0, max - doneLastHour);
  if (!budget) return 0;
  const todo = await prisma.newsItem.findMany({
    where: { importance: { gte: 4 }, isPrimary: true, analysis: null, publishedAt: { gte: new Date(Date.now() - 12 * 3600_000) } },
    orderBy: [{ importance: "desc" }, { publishedAt: "desc" }],
    take: budget,
  });
  let n = 0;
  for (const t of todo) {
    try { await analyzeNews(t.id); n++; } catch (e) { console.error("[ai] analysis failed", t.id, (e as Error).message); }
  }
  return n;
}
